package calculadora;

/**
 *
 * @author Dheniel 
 */
public class Calculos {
    public double fazerSoma(double numeroUm, double numeroDois){
        double resultadoSoma = numeroUm + numeroDois;
        return resultadoSoma;
    }
    public double fazerSubtracao(double numeroUm, double numeroDois){
        double resultadoSubtracao = numeroUm - numeroDois;
        return resultadoSubtracao;
    }
    public double fazerMultiplicacao(double numeroUm, double numeroDois){
        double resultadoMultiplicacao = numeroUm * numeroDois;
        return resultadoMultiplicacao;
    }
    public double fazerDivisao(double numeroUm, double numeroDois){
        double resultadoDivisao = numeroUm / numeroDois;
        return resultadoDivisao;
    }
}
